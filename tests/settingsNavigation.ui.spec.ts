import { test, expect } from './support/paletteUI';

for (const overlay of [false, true]) test(`settings navigation preserves categories, search and drafts in ${overlay ? 'overlay' : 'window'}`, async ({ palette }) => {
  const { ui } = palette;
  await palette.open({ locale: 'en-US', ...(overlay ? { overlay: true as const } : {}) });
  const surface = overlay ? ui.frameLocator('.justonehop-frame') : ui;
  await surface.locator('.settings-button').click();
  const settings = surface.locator('.settings-view');
  const search = surface.getByRole('textbox', { name: 'Search settings', exact: true });
  const help = surface.getByRole('tab', { name: 'Help', exact: true });
  const appearance = surface.getByRole('tab', { name: 'Appearance', exact: true });
  await expect(search).toBeFocused();
  await expect(appearance).toHaveAttribute('aria-selected', 'true');
  await expect(surface.getByRole('tab', { name: 'General', exact: true })).toHaveCount(0);
  await expect(settings.locator('.settings-body h2')).toHaveCount(0);
  await expect(settings.locator('.settings-appearance')).toHaveCSS('border-radius', '12px');
  await expect(settings.locator('.settings-body')).toHaveCSS('padding', '16px');
  await expect(settings.locator('.settings-appearance')).toHaveCSS('padding-left', '12px');
  await expect(settings.locator('[data-setting="language"] label')).toHaveCSS('font-size', '13px');
  await expect(settings.locator('[data-setting="language"] p')).toHaveCSS('font-size', '12px');
  const language = surface.getByRole('combobox', { name: 'Language', exact: true });
  await expect(language).toBeVisible();
  await search.press('Tab'); await surface.locator('.settings-search .search-dismiss').press('Tab');
  await expect(appearance).toBeFocused();
  await appearance.press('ArrowDown'); await expect(surface.getByRole('tab', { name: 'Keyboard', exact: true })).toBeFocused();
  await surface.getByRole('tab', { name: 'Keyboard', exact: true }).press('ArrowUp');
  await expect(appearance).toBeFocused();
  const theme = surface.getByRole('combobox', { name: 'Theme', exact: true });
  await appearance.press('Tab'); await expect(language).toBeFocused();
  await language.press('Tab'); await expect(theme).toBeFocused();
  await theme.press('Enter'); await theme.press('End'); await theme.press('Enter');
  await expect(theme).toHaveText('Dark');
  await expect(settings).toHaveCSS('background-color', 'rgb(41, 42, 45)');
  await settings.screenshot({ path: test.info().outputPath('settings-sidebar-dark.png') });
  await theme.press('Enter'); await theme.press('Home'); await theme.press('Enter');
  await ui.emulateMedia({ colorScheme: 'light' });
  await settings.screenshot({ path: test.info().outputPath('settings-sidebar-light.png') });

  await surface.getByRole('tab', { name: 'Labs', exact: true }).click();
  const tuck = surface.locator('[data-setting="tabs"]');
  const ranking = surface.locator('[data-setting="ranking"]');
  await expect(tuck).toHaveCSS('border-radius', '12px');
  await expect(ranking).toHaveCSS('border-radius', '12px');
  const tuckBox = await tuck.boundingBox(), rankingBox = await ranking.boundingBox();
  expect(rankingBox!.y - tuckBox!.y - tuckBox!.height).toBeGreaterThanOrEqual(12);
  for (const label of await surface.locator('.settings-category-list button span').all()) {
    expect(await label.evaluate(node => node.getBoundingClientRect().height <= parseFloat(getComputedStyle(node).lineHeight) + 1)).toBe(true);
  }
  await settings.screenshot({ path: test.info().outputPath('settings-labs-cards.png') });
  await surface.getByRole('switch', { name: 'Auto Tuck Tabs' }).click();
  const duration = surface.getByRole('combobox', { name: 'Tuck after inactivity' });
  await expect(duration).toHaveText('7 days');
  await expect(surface.locator('.tuck-status-summary')).toHaveText('No tabs currently qualify');
  const labelBox = await surface.locator('.tuck-duration-label').boundingBox(), durationBox = await duration.boundingBox();
  expect(Math.abs(labelBox!.y + labelBox!.height / 2 - durationBox!.y - durationBox!.height / 2)).toBeLessThan(2);
  const statusBox = await surface.locator('.tuck-status-details').boundingBox();
  const refresh = surface.getByRole('button', { name: 'Refresh status' });
  const refreshBox = await refresh.boundingBox();
  expect(refreshBox!.x).toBeGreaterThanOrEqual(statusBox!.x + statusBox!.width);
  expect(Math.abs(refreshBox!.y - statusBox!.y)).toBeLessThan(2);
  await duration.focus(); await duration.press('Tab'); await expect(refresh).toBeFocused();
  await refresh.press('Tab'); await expect(surface.getByRole('button', { name: 'How it works' })).toBeFocused();
  await settings.screenshot({ path: test.info().outputPath('settings-tuck-compact.png') });
  await surface.getByRole('button', { name: 'How it works' }).click();
  await expect(surface.locator('.tuck-rules-copy li')).toHaveCount(4);
  await surface.locator('.settings-body').evaluate(node => { node.scrollTop = 0; });
  await settings.screenshot({ path: test.info().outputPath('settings-tuck-expanded.png') });
  for (const node of await surface.locator('.tuck-settings, .tuck-rules-copy').all()) {
    expect(await node.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  }
  await surface.getByRole('tab', { name: 'Keyboard', exact: true }).click();
  await expect(surface.locator('[data-setting="keyboard"] p')).toHaveText('The only shortcut you need to remember. Search for any feature from here.');
  expect(await surface.locator('[data-setting="keyboard"]').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  await settings.screenshot({ path: test.info().outputPath('settings-keyboard.png') });
  await appearance.click();
  const change = surface.getByRole('button', { name: 'Wear Badge' });
  await change.click();
  const emoji = surface.getByRole('textbox', { name: 'Emoji', exact: true });
  await expect(emoji).toBeFocused(); await emoji.fill('🌱');
  await expect(settings.locator('.search-bar')).toHaveCount(1);
  await expect(settings.locator('.palette-footer')).toHaveCount(1);
  await expect(settings.locator('.task-header')).toHaveCount(0);
  await search.fill('language');
  await expect(settings.locator('.settings-body h2')).toHaveText('Appearance');
  await expect(surface.getByRole('combobox', { name: 'Language', exact: true })).toBeVisible();
  await expect(surface.getByRole('tab', { selected: true })).toHaveCount(0);
  await expect(emoji).not.toBeVisible();
  await search.press('Escape');
  await expect(search).toHaveValue(''); await expect(emoji).toHaveValue('🌱');
  await expect(appearance).toHaveAttribute('aria-selected', 'true');
  await expect(settings.locator('.palette-footer')).toHaveCount(1);
  await settings.screenshot({ path: test.info().outputPath('settings-icon-detail.png') });
  await surface.locator('.settings-footer').getByRole('button', { name: 'Back', exact: true }).click();
  await expect(change).toBeFocused();
  await change.click(); await expect(emoji).toHaveValue('');
  await appearance.click();
  await expect(surface.locator('.search-icon-settings')).toHaveCount(0);

  await search.fill('emoji');
  await search.evaluate((node: HTMLInputElement) => node.setSelectionRange(1, 4));
  await change.click(); await emoji.fill('🚀');
  await surface.getByRole('button', { name: 'Wear Badge' }).click();
  await expect(search).toHaveValue('emoji'); await expect(change).toBeFocused();
  expect(await search.evaluate((node: HTMLInputElement) => [node.selectionStart, node.selectionEnd])).toEqual([1, 4]);
  await search.press('Escape'); await expect(appearance).toHaveAttribute('aria-selected', 'true');
  await search.fill('help');
  await surface.getByRole('button', { name: 'Read Help', exact: true }).click();
  await expect(settings.locator('.palette-footer-title')).toHaveText('Settings · Help');
  await surface.locator('.settings-footer').getByRole('button', { name: 'Back', exact: true }).click();
  await expect(search).toHaveValue('help');
  await help.click();
  await expect(surface.getByRole('article', { name: 'Help', exact: true })).toBeFocused();
  await expect(settings.locator('.search-bar')).toHaveCount(1);
  await settings.screenshot({ path: test.info().outputPath('settings-help.png') });
  await search.fill('theme');
  await expect(theme).toBeVisible();
  await search.press('Escape');
  await expect(surface.getByRole('article', { name: 'Help', exact: true })).toBeVisible();
  await surface.locator('.settings-footer').getByRole('button', { name: 'Back', exact: true }).click();
  await expect(surface.getByRole('combobox', { name: 'Search commands, tabs, bookmarks, and history' })).toBeFocused();
  await surface.locator('.settings-button').click();

  await ui.setViewportSize({ width: 390, height: 600 });
  if (!overlay) await ui.locator('.justonehop-app').evaluate(node => { node.classList.replace('popup', 'overlay'); document.body.style.width = '390px'; });
  const categories = surface.getByRole('combobox', { name: 'Settings categories' });
  await expect(categories).toBeVisible();
  await categories.selectOption('appearance'); await change.click();
  await expect(search).toBeInViewport();
  await expect(surface.getByRole('button', { name: 'Wear Badge' })).toBeInViewport();
  await expect(surface.locator('.settings-footer').getByRole('button', { name: 'Back', exact: true })).toBeInViewport();
  expect(await settings.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  await settings.screenshot({ path: test.info().outputPath('settings-narrow.png') });
  await emoji.press('Escape'); await expect(change).toBeFocused();
  await change.press('Escape');
  await expect(surface.getByRole('combobox', { name: 'Search commands, tabs, bookmarks, and history' })).toBeFocused();
});
