import { chromium } from '@playwright/test';
import { mkdtemp, readdir, rm } from 'node:fs/promises';
import { homedir, tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createServer } from 'node:http';
const server = createServer((req, res) => { const name = req.url.slice(1) || 'A'; res.setHeader('Content-Type','text/html'); res.end(`<title>JustOneHop Switcher ${name}</title><h1>JustOneHop Switcher ${name}</h1><p>Disposable recent-tab test fixture.</p><input aria-label="Typing target">`); });
await new Promise(r => server.listen(0,'127.0.0.1',r));
const origin = `http://127.0.0.1:${server.address().port}`;
const cache = join(homedir(),'Library/Caches/ms-playwright');
const version = (await readdir(cache)).filter(x => /^chromium-\d+$/.test(x)).sort().reverse()[0];
const profile = await mkdtemp(join(tmpdir(),'justonehop-switcher-manual-'));
const extension = resolve('dist');
const context = await chromium.launchPersistentContext(profile, {headless:false,viewport:null,executablePath:join(cache,version,'chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing'),args:[`--disable-extensions-except=${extension}`,`--load-extension=${extension}`]});
const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
const pages=[];
for (const name of ['A','B','C']) { const page=await context.newPage();await page.goto(`${origin}/${name}`);pages.push(page); }
await pages[0].bringToFront();
console.log(JSON.stringify({origin,extension:worker.url(),profile}));
const finish = async () => { await context.close();server.close();await rm(profile,{recursive:true,force:true});process.exit(); };
process.on('SIGINT',finish);process.on('SIGTERM',finish);
await new Promise(()=>{});
